/** 盘面 Section → Markdown */
export function sectionsToMarkdown(sections: SectionLike[]): string {
  return sections.map((s) => {
    const lines: string[] = [`### ${s.title}`];
    if (s.warn?.length) for (const w of s.warn) lines.push(`> ⚠ ${w}`);
    if (s.kv?.length) for (const [k, v] of s.kv) lines.push(`- **${k}**: ${v}`);
    if (s.headers && s.rows) {
      lines.push(`| ${s.headers.join(" | ")} |`, `| ${s.headers.map(() => "---").join(" | ")} |`);
      for (const r of s.rows) lines.push(`| ${r.join(" | ")} |`);
    }
    if (s.text?.length) for (const t of s.text) lines.push(t);
    return lines.join("\n");
  }).join("\n\n");
}

export interface PromptInput {
  moduleIds: string[];
  moduleNames: Record<string, string>;
  sections: Record<string, SectionLike[]>;
  question?: string;
  focus?: string;
  scopeNote?: string;
}

/** 组装 user prompt: 用户输入 + 盘面 + 该模块的解读锚点 */
export function buildUserPrompt(p: PromptInput): string {
  const parts: string[] = [];
  parts.push("## 用户输入");
  parts.push(`勾选模块: ${p.moduleIds.map((id) => p.moduleNames[id] ?? id).join("、")}`);
  if (p.question) parts.push(`用户想问: ${p.question}`);
  if (p.focus) parts.push(`关注领域: ${p.focus}`);
  if (p.scopeNote) parts.push(`范围说明: ${p.scopeNote}`);

  parts.push("\n## 程序排盘结果(已精确计算,禁止改动任何数字/干支/日期)");
  for (const id of p.moduleIds) {
    const secs = p.sections[id];
    if (!secs?.length) continue;
    parts.push(`\n#### 模块: ${p.moduleNames[id] ?? id}\n${sectionsToMarkdown(secs)}`);
    const anchor = MODULE_ANCHORS[id];
    if (anchor) parts.push(`\n【本模块解读锚点清单】${anchor}`);
  }

  parts.push("\n## 输出要求");
  parts.push("- 按系统提示的输出结构组织;优先回应用户的问题/关注领域");
  parts.push("- 用户没让细讲的杂项模块用简表带过");
  parts.push("- 两个系统(西占/八字等)结论一致才可说\"确定性高\",冲突处明说两套口径");
  parts.push("- 结尾一字不改输出免责声明固定文案");
  return parts.join("\n");
}
